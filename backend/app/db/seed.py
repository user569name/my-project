def _split_keywords(value: str) -> list[str]:
    return [keyword.strip() for keyword in value.split(",") if keyword.strip()]


def build_deck() -> list[TarotCard]:
    cards: list[TarotCard] = []

    for number, slug, name, name_ru, kw_up, kw_rev, meaning_up, meaning_rev in MAJOR_ARCANA:
        cards.append(
            TarotCard(
                slug=slug,
                name=name,
                name_ru=name_ru,
                arcana="major",
                suit=None,
                number=number,
                symbol=ROMAN_NUMERALS[number],
                keywords_upright=_split_keywords(kw_up),
                keywords_reversed=_split_keywords(kw_rev),
                meaning_upright=meaning_up,
                meaning_reversed=meaning_rev,
            )
        )

    for (
        suit_slug,
        suit_en,
        _suit_ru,
        suit_genitive,
        symbol,
        suit_keywords,
        suit_up,
        suit_rev,
    ) in SUITS:
        for rank_slug, rank_en, rank_ru, rank_number, rank_keywords, rank_up, rank_rev in RANKS:
            cards.append(
                TarotCard(
                    slug=f"{rank_slug}-of-{suit_slug}",
                    name=f"{rank_en} of {suit_en}",
                    name_ru=f"{rank_ru} {suit_genitive}",
                    arcana="minor",
                    suit=suit_slug,
                    number=rank_number,
                    symbol=symbol,
                    keywords_upright=[*rank_keywords, *suit_keywords],
                    keywords_reversed=["блок", "задержка", *suit_keywords],
                    meaning_upright=f"{rank_up} {suit_up}",
                    meaning_reversed=f"{rank_rev} {suit_rev}",
                )
            )

    return cards


async def seed_tarot_cards(session: AsyncSession) -> int:
    """Insert the deck once. Returns the number of inserted cards."""
    existing = await session.scalar(select(func.count()).select_from(TarotCard))
    if existing:
        return 0

    cards = build_deck()
    if len(cards) != 78:
        raise RuntimeError(f"Tarot deck must contain 78 cards, got {len(cards)}")

    session.add_all(cards)
    await session.commit()
    return len(cards)
