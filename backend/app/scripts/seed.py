def seed():
    db = SessionLocal()
    try:
        if db.query(TarotCard).count() > 0:
            print("[OK] База уже содержит карты. Пропускаем.")
            return
        
        # Старшие арканы
        for name, num, kw, upright, reversed_ in MAJOR_ARCANA:
            db.add(TarotCard(
                name=name, arcana="major", number=num,
                keywords=kw, meaning_upright=upright, meaning_reversed=reversed_,
                image_url=f"/static/cards/major_{num}.jpg"
            ))
        
        # Младшие арканы
        for suit_key, suit_ru in MINOR_SUITS.items():
            kw, upright, reversed_ = MEANINGS[suit_key]
            for i, rank in enumerate(RANKS):
                db.add(TarotCard(
                    name=f"{rank} {suit_ru}",
                    arcana="minor", suit=suit_key, number=i,
                    keywords=kw, meaning_upright=upright, meaning_reversed=reversed_,
                    image_url=f"/static/cards/{suit_key}_{i}.jpg"
                ))
        
        db.commit()
        print(f"[OK] Загружено {db.query(TarotCard).count()} карт Таро")
    finally:
        db.close()

if __name__ == "__main__":
    seed()